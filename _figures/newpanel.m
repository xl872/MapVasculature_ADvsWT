function f = newpanel(w_in, h_in)
%NEWPANEL  Invisible white figure of exactly w_in x h_in inches.
f = figure('Visible','off','Color','w','Units','inches', ...
    'Position',[1 1 w_in h_in],'PaperUnits','inches', ...
    'PaperSize',[w_in h_in],'PaperPosition',[0 0 w_in h_in], ...
    'InvertHardcopy','off','Renderer','painters');
end
